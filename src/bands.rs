/// Named band containing `hz`, if any.
pub fn name(hz: f64) -> Option<&'static str> {
    BANDS
        .iter()
        .find(|(_, lo, hi)| (lo * 1e6..=hi * 1e6).contains(&hz))
        .map(|(b, _, _)| *b)
}
